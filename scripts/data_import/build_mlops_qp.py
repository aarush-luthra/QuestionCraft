def bloom_fields(bt):
    if isinstance(bt, str):  # multi-level, e.g. "3,4" -> keep highest, record raw
        levels = [int(x) for x in bt.split(",")]
        top = max(levels)
        return f"L{top}", BLOOM[top], bt
    return f"L{bt}", BLOOM[bt], None


